r,p,l,o,circ=kit.rect,kit.poly,kit.line,kit.oval,kit.circ

def plant(c,x,y):
    r(c,x-33,y-20,x+33,y+28,'#9E927E',3,5)
    o(c,x-33,y-27,x+33,y-13,'#B5A997',2)
    for dx,dy in [(-60,-105),(-47,-138),(-20,-141),(2,-160),(30,-137),(54,-111),(62,-72),(-54,-66)]:
        l(c,x,y-17,x+dx,y+dy,2,'#4F6279')
        c.save()
        c.translate(x+dx,y+dy)
        c.rotate(dx/4)
        o(c,-10,-20,10,20,'#667D90',1)
        l(c,0,-17,0,16,1,'#A7B6C2')
        c.restore()

def guest_chair(c,x,y,scale=1):
    c.save()
    c.translate(x,y)
    c.scale(scale,scale)
    o(c,-80,55,82,74,'#59677C',0)
    for dx in [-49,49]:
        l(c,dx,37,dx-8,95,7,INK)
        l(c,dx,37,dx+15,95,7,INK)
        circ(c,dx-8,95,4,'#AD9F87',1)
    r(c,-66,-64,66,37,'#8995A2',4,20)
    r(c,-57,-58,57,25,'#C1BDB2',2,14)
    for yy in [-38,-13,12]:
        l(c,-51,yy,51,yy,1.3,'#888D93')
    p(c,[(-75,15),(75,15),(82,48),(64,61),(-64,61),(-82,48)],'#AAB0B0',3)
    p(c,[(-75,6),(-61,6),(-53,35),(-56,50),(-77,44)],'#D1C7B7',2)
    p(c,[(75,6),(61,6),(53,35),(56,50),(77,44)],'#D1C7B7',2)
    c.restore()

